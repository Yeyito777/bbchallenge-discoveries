#!/usr/bin/env python3
"""Writes BBminus2x4/Deciders/Table_Params.v and BBminus2x4/Deciders/ClosedAut_Certificates.v.

usage: gen_table.py ASSIGN CERTS.xz [NCHUNKS]

ASSIGN has one line per machine: `<tm> <spec>` with spec one of
  ng2 L R GAS | ng1 H L R GAS | lru L R GAS | rwl LEN MIN MAXT GAS | aut
`aut` machines take their closed automaton certificate from CERTS.xz (least-verify dump format).
Nothing here is trusted: Rocq runs each entry through a decider proved sound for all machines.
"""
import os
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
proj = os.path.join(here, '..', 'BBminus2x4')


def trans_name(t):
    if t == '---':
        return 'HR1'
    return f'{t[2]}{t[1]}{t[0]}'


def make_tm(m):
    """The machine's key for `find_entry`: its 8 transitions A0..A3 B0..B3."""
    s = m.replace('_', '')
    return '(' + '::'.join(trans_name(s[3 * i:3 * i + 3]) for i in range(8)) + '::nil)'


def entry(spec):
    p = spec.split()
    k, a = p[0], p[1:]
    ctor = {'ng2': 'TE_NG2', 'ng1': 'TE_NG1', 'lru': 'TE_LRU', 'rwl': 'TE_RWL'}[k]
    return f'{ctor} ' + ' '.join(v + '%N' for v in a)


def main():
    rows = []
    for line in open(sys.argv[1]):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        tm, spec = line.split(None, 1)
        rows.append((tm, spec.strip()))
    params = [(tm, s) for tm, s in rows if s != 'aut']
    auts = [tm for tm, s in rows if s == 'aut']
    with open(os.path.join(proj, 'Deciders', 'Table_Params.v'), 'w') as f:
        f.write('(** Per-machine decider parameters (generated by tools/gen_table.py from the parameter sweep). *)\n\n')
        f.write('Require Import List.\nRequire Import NArith.\n\nFrom BBminus2x4 Require Import BBminus2x4_Statement.\nFrom BBminus2x4 Require Import TM.\n'
                'From BBminus2x4 Require Import BB2x4_Make_TM.\nFrom BBminus2x4 Require Import Decider_Table.\n\n'
                'Set Warnings "-abstract-large-number".\n\n')
        # blocks of 100 entries joined with `concat`, so coqc and the native compiler stay within a default stack
        f.write('Definition table_params : list (TM_key * TableEntry) := concat (\n')
        for i in range(0, len(params), 100):
            f.write('(\n')
            for tm, s in params[i:i + 100]:
                f.write(f'(* {tm} *) ({make_tm(tm)}, {entry(s)})::\n')
            f.write('nil)::\n')
        f.write('nil).\n')
    with tempfile.NamedTemporaryFile('w', delete=False) as t:
        t.write('\n'.join(auts) + '\n')
    nchunks = sys.argv[3] if len(sys.argv) > 3 else '1'
    subprocess.run([sys.executable, os.path.join(here, 'certs_to_coq.py'), t.name, sys.argv[2],
                    os.path.join(proj, 'Deciders', 'ClosedAut_Certificates.v'), nchunks], check=True)
    # _CoqProject: list the certificate parts before ClosedAut_Certificates.v
    cp = os.path.join(proj, '_CoqProject')
    lines = [l for l in open(cp).read().split('\n') if not l.startswith('Deciders/ClosedAut_Certificates_')]
    i = lines.index('Deciders/ClosedAut_Certificates.v')
    if int(nchunks) > 1:
        lines[i:i] = [f'Deciders/ClosedAut_Certificates_{k}.v' for k in range(int(nchunks))]
    open(cp, 'w').write('\n'.join(lines))
    os.unlink(t.name)
    print(f'{len(params)} parameter entries, {len(auts)} certificates', file=sys.stderr)


main()
