#!/usr/bin/env python3
"""Writes the parallel TNF enumeration files of BBminus2x4.

usage: gen_split.py [--stub] [ITERS] INNER...

Each INNER is a path of child indices from the root ("" for the root itself, "2", "2.5", ...). Inner nodes are
split into their children; every child of an inner node that is not itself inner becomes a leaf file
TNF_Roots/Leaf_<path>.v proving its bound by running the search to an empty queue. Inner nodes are assembled in
TNF_Roots/Inner_<path>.v and the root in TNF_Enumeration.v. Child counts are computed here with a small Python
model of TNF_Node_expand (state/symbol normalisation on 110[1]011); Rocq re-checks each count, so a wrong model
only makes the build fail, it cannot make the proof unsound.
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
proj = os.path.join(here, '..', 'BBminus2x4')
args = sys.argv[1:]
STUB = '--stub' in args
args = [a for a in args if a != '--stub']
ITERS = 4000
if args and args[0].isdigit() and len(args[0]) >= 3:
    ITERS = int(args.pop(0))
inner = [tuple(int(v) for v in a.split('.')) if a else () for a in args] or [()]
inner = sorted(set(inner) | {()}, key=lambda p: (len(p), p))

TAPE = {-3: 1, -2: 1, -1: 0, 0: 1, 1: 0, 2: 1, 3: 1}
# Trans_list order of BB2x4_Make_TM.v: state, then direction (L before R), then symbol
TRANS = [(s, d, w) for s in (0, 1) for d in ('L', 'R') for w in range(4)]


def halt_point(tm):
    """(state, symbol) of the first undefined transition from the start tape, or None."""
    tape, pos, st = dict(TAPE), 0, 0
    for _ in range(10000):
        sym = tape.get(pos, 0)
        t = tm.get((st, sym))
        if t is None:
            return st, sym
        w, d, s1 = t
        tape[pos] = w
        pos += 1 if d == 'R' else -1
        st = s1
    return None


def children(tm):
    hp = halt_point(tm)
    if hp is None or len(tm) == 7:
        return []
    s, i = hp
    free23 = i in (0, 1) and all(k[1] in (0, 1) and v[0] in (0, 1) for k, v in tm.items())
    out = []
    for (s1, d, w) in TRANS:
        if free23 and w == 3:
            continue
        t2 = dict(tm)
        t2[(s, i)] = (w, d, s1)
        out.append(t2)
    return out


def node(path):
    tm = {}
    for j in path:
        tm = children(tm)[j]
    return tm


def name(p):
    return 'r' + ''.join('_' + str(j) for j in p)


def coq_path(p):
    return '(' + ''.join(f'{j}::' for j in p) + 'nil)'


roots_dir = os.path.join(proj, 'TNF_Roots')
os.makedirs(roots_dir, exist_ok=True)
for f in os.listdir(roots_dir):
    if f.endswith('.v'):
        os.remove(os.path.join(roots_dir, f))

hdr = """Require Import Lia.
Require Import List.

From BBminus2x4 Require Import TNF.
From BBminus2x4 Require Import TNF_Common.
"""
leaves = []
inner_set = set(inner)
for p in inner:
    for j in range(len(children(node(p)))):
        if p + (j,) not in inner_set:
            leaves.append(p + (j,))

for p in leaves:
    n = name(p)
    body = ('Admitted. (* STUB *)' if STUB else
            '  native_cast_no_check (eq_refl (@nil TNF_Node, @nil TNF_Node)).\nQed.')
    with open(os.path.join(roots_dir, f'Leaf{n[1:]}.v'), 'w') as f:
        f.write(f"""(** Leaf subtree {coq_path(p)} (generated by tools/gen_split.py). *)
{hdr}
Lemma {n}_empty:
  Nat.iter {ITERS} q_suc (SearchQueue_init (node_at {coq_path(p)})) = (nil,nil).
Proof.
{body}

Lemma {n}_HTUB:
  TNF_Node_HTUB BB (node_at {coq_path(p)}).
Proof.
  apply (leaf_HTUB _ {ITERS}).
  apply {n}_empty.
Qed.
""")


def child_modules(p):
    k = len(children(node(p)))
    mods = []
    for j in range(k):
        c = p + (j,)
        mods.append(('Inner' if c in inner_set else 'Leaf') + name(c)[1:])
    return k, mods


for p in sorted(inner, key=lambda p: -len(p)):
    k, mods = child_modules(p)
    imports = '\n'.join(f'From BBminus2x4 Require Import TNF_Roots.{m}.' for m in mods)
    pat = ''.join('[|' for _ in range(k)) + 'j' + ''.join(']' for _ in range(k))
    cases = '\n'.join(f'  - apply {name(p + (j,))}_HTUB.' for j in range(k))
    proof = f"""Lemma {name(p)}_HTUB:
  TNF_Node_HTUB BB (node_at {coq_path(p)}).
Proof.
  apply (inner_HTUB _ {k}).
  - vm_compute. reflexivity.
  - vm_compute. reflexivity.
  - intros j Hj.
    destruct j as {pat}.
{cases}
    + lia.
Qed.
""".replace('\n  - apply', '\n    + apply')
    target = os.path.join(proj, 'TNF_Enumeration.v') if p == () else os.path.join(roots_dir, f'Inner{name(p)[1:]}.v')
    extra = ''
    if p == ():
        extra = """
Lemma TM0_HTUB:
  HaltTimeUpperBound Σ BB StartES (LE Σ TM0).
Proof.
  apply r_HTUB.
Qed.

(** Every 2x4 machine that halts from the start tape halts within BB steps (Coq-BB5's `HaltsAt` convention). *)
Lemma allTM_HTUB:
  HaltTimeUpperBound Σ BB StartES (fun _ => True).
Proof.
  unfold HaltTimeUpperBound.
  intros.
  eapply TM0_HTUB.
  2: apply H0.
  unfold LE.
  intros.
  right.
  reflexivity.
Qed.
"""
    with open(target, 'w') as f:
        f.write(f"""(** {'Root of the parallel TNF enumeration' if p == () else 'Inner node ' + coq_path(p)} (generated by tools/gen_split.py). *)
Require Import Lia.
Require Import List.
Require Import ZArith.

From BBminus2x4 Require Import BBminus2x4_Statement.
From BBminus2x4 Require Import TM.
From BBminus2x4 Require Import TNF.
From BBminus2x4 Require Import TNF_Common.
{imports}

{proof}{extra}""")

# _CoqProject: replace the TNF_Roots / TNF_Enumeration block
cp = os.path.join(proj, '_CoqProject')
lines = [l for l in open(cp).read().split('\n') if not l.startswith('TNF_Roots/') and l != 'TNF_Enumeration.v']
i = lines.index('TNF_Common.v')
files = [f'TNF_Roots/Leaf{name(p)[1:]}.v' for p in leaves] + \
        [f'TNF_Roots/Inner{name(p)[1:]}.v' for p in sorted(inner, key=lambda p: -len(p)) if p != ()] + ['TNF_Enumeration.v']
lines[i + 1:i + 1] = files
open(cp, 'w').write('\n'.join(lines))
print(f'{len(leaves)} leaves, {len(inner)} inner nodes, {ITERS} iterations' + (' (STUB)' if STUB else ''))
