#!/usr/bin/env python3
"""Write the Rocq data files of the n = 7 proof from the version-4 jobs (tools/n7_assemble.py).

usage: n7_to_coq.py JOBDIR OUTDIR

Writes OUTDIR/Wang7_Prefixes.v (the reset prefixes and their owners), OUTDIR/Tori7_cK.v and
OUTDIR/Tori7.v (the shared torus table), OUTDIR/Job7_jJJJ_cK.v and Job7_jJJJ_sK.v (job JJJ's coded
tokens and code table, 2^16 integers per file) and OUTDIR/Check7_jJJJ.v (the job's certificate and the lemma that it passes),
and prints the job count. Each file starts with the SHA-256 of what it was made from."""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wtcoq import HEAD, array_lit, chunks, huffman_encode, leb_tokens, outer_lit, pack_tori

jd, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)
sha = lambda path: hashlib.sha256(open(path, "rb").read()).hexdigest()
rp = os.path.join(jd, "refs7.txt")
lines = open(rp).read().split("\n")
head = lines[0].split()
assert head[:2] == ["wt-refs", "4"] and head[3] == "7" and head[5] == "17" and head[9] == "10", head
jobs, gate = int(head[11]), int(head[13])
rows = [list(map(int, l.split())) for l in lines[1:] if l.strip()]
assert len(rows) == int(head[15])

with open(os.path.join(out, "Wang7_Prefixes.v"), "w") as f:
    f.write("(* generated by tools/n7_to_coq.py from refs7.txt, sha256 %s *)\n" % sha(rp))
    f.write("(** The labels of cells 0..9 at each of the %d reset nodes, in walk order, and the job that\n"
            "    walks each one (%d jobs). *)\n" % (len(rows), jobs))
    f.write("From Coq Require Import List Arith.\nImport ListNotations.\nFrom WangTiles Require Import Wang_Upper.\n\n")
    names = []
    for j in range(0, len(rows), 500):
        nm = "refs7_%d" % (j // 500)
        names.append(nm)
        f.write("Definition %s : list (list nat) := [%s].\n" % (nm, ";".join("[" + ";".join(map(str, r[1:])) + "]" for r in rows[j:j + 500])))
    f.write("\nDefinition refs7 : list (list nat) := %s.\n" % " ++ ".join(names))
    onames = []
    for j in range(0, len(rows), 2000):
        nm = "owners7_%d" % (j // 2000)
        onames.append(nm)
        f.write("Definition %s : list nat := [%s].\n" % (nm, ";".join(str(r[0]) for r in rows[j:j + 2000])))
    f.write("Definition owners7 : list nat := %s.\n\n" % " ++ ".join(onames))
    f.write("(** Every prefix appears once. *)\nLemma refs7_nodup : NoDup refs7.\n"
            "Proof. apply nodup_lists_spec. native_cast_no_check (eq_refl true). Qed.\n\n")
    f.write("(** Every owner is one of the %d jobs. *)\nLemma owners7_bound : forall i, nth i owners7 0 < %d.\n"
            "Proof. apply owners_bound; [apply Nat.ltb_lt; reflexivity|vm_compute; reflexivity]. Qed.\n" % (jobs, jobs))

tp = os.path.join(jd, "tori7.txt")
tl = open(tp).read().split("\n")
assert tl[0].startswith("wt-tori 4 n 7 count "), tl[0]
tori = [list(map(int, l.split())) for l in tl[1:] if l.strip()]
assert len(tori) == int(tl[0].split()[-1])
tdata, toff = pack_tori(tori)
tnames = []
for kind, xs in (("d", tdata), ("o", toff)):
    for k, ch in enumerate(chunks(xs)):
        nm = "tori7_%s%d" % (kind, k)
        tnames.append((kind, nm))
        with open(os.path.join(out, "Tori7_%s%d.v" % (kind, k)), "w") as f:
            f.write("(* generated by tools/n7_to_coq.py from tori7.txt, sha256 %s *)\n" % sha(tp))
            f.write(HEAD + "Local Open Scope uint63_scope.\n\n")
            f.write("Definition %s : array int := %s.\n" % (nm, array_lit(ch)))
with open(os.path.join(out, "Tori7.v"), "w") as f:
    f.write("(* generated by tools/n7_to_coq.py from tori7.txt, sha256 %s *)\n" % sha(tp))
    f.write("(** The torus table shared by all jobs: %d tori. *)\n" % len(tori))
    f.write(HEAD + "From WangTiles.n7 Require Import %s.\nLocal Open Scope uint63_scope.\n\n" % " ".join("Tori7_" + nm[6:] for _, nm in tnames))
    f.write("Definition ntori7 : int := %d.\n" % len(tori))
    f.write("Definition tdata7 : array (array int) := %s.\n" % outer_lit([nm for k, nm in tnames if k == "d"]))
    f.write("Definition toff7 : array (array int) := %s.\n" % outer_lit([nm for k, nm in tnames if k == "o"]))

caches = dict(tuple(map(int, l.split())) for l in open(os.path.join(jd, "caches.txt")) if l.strip())


def job(j):
    tp_ = os.path.join(jd, "job_%03d.tree" % j)
    toks = leb_tokens(open(tp_, "rb").read())
    words, syms, counts = huffman_encode(toks)
    used = [int(x) for x in open(os.path.join(jd, "job_%03d.used" % j)).read().split()]
    hdr = "(* generated by tools/n7_to_coq.py from job_%03d.tree, sha256 %s *)\n" % (j, sha(tp_))
    files = []
    for kind, xs in (("c", words), ("s", syms)):
        for k, ch in enumerate(chunks(xs)):
            nm = "job7_j%03d_%s%d" % (j, kind, k)
            files.append((kind, nm))
            with open(os.path.join(out, "Job7_j%03d_%s%d.v" % (j, kind, k)), "w") as f:
                f.write(hdr + HEAD + "Local Open Scope uint63_scope.\n\n")
                f.write("Definition %s : array int := %s.\n" % (nm, array_lit(ch)))
    with open(os.path.join(out, "Check7_j%03d.v" % j), "w") as f:
        f.write(hdr + HEAD + "From WangTiles Require Import Wang_Checker.\n")
        f.write("From WangTiles.n7 Require Import Wang7_Prefixes Tori7 %s.\n" % " ".join("Job7_j%03d_%s%s" % (j, nm.split("_")[-1][0], nm.split("_")[-1][1:]) for _, nm in files))
        f.write("Local Open Scope uint63_scope.\n\n")
        f.write("Definition tused7_j%03d : array int := %s.\n" % (j, array_lit(used)))
        f.write("Definition hcount7_j%03d : array int := %s.\n" % (j, array_lit(counts)))
        f.write("\nDefinition cert7_j%03d : cert := mkCert 7 17 10 %d %d %s %d hcount7_j%03d %s ntori7 tdata7 toff7 tused7_j%03d %d %d.\n\n"
                % (j, j, gate, outer_lit([nm for k, nm in files if k == "c"]), len(toks), j,
                   outer_lit([nm for k, nm in files if k == "s"]), j, len(used), caches[j]))
        f.write("(** Job %d of the n = 7, D = 17 certificate passes the checker. *)\n" % j)
        f.write("Lemma job7_j%03d_ok : check refs7 owners7 cert7_j%03d = true.\n" % (j, j))
        f.write("Proof. native_cast_no_check (eq_refl true). Time Qed.\n")
    return len(toks), len(words)


from multiprocessing import Pool
with Pool(int(os.environ.get("PAR", "4"))) as pool:
    stats = pool.map(job, range(jobs))
print("tokens", sum(a for a, b in stats), "integers", sum(b for a, b in stats), file=sys.stderr)

with open(os.path.join(out, "Jobs7.v"), "w") as f:
    f.write("(* generated by tools/n7_to_coq.py: the %d jobs of the n = 7 certificate *)\n" % jobs)
    f.write("From Coq Require Import List.\nImport ListNotations.\nFrom WangTiles Require Import Wang_Checker Wang_Upper.\n")
    f.write("From WangTiles.n7 Require Import Wang7_Prefixes %s.\n\n" % " ".join("Check7_j%03d" % j for j in range(jobs)))
    f.write("Definition njobs7 : nat := %d.\n" % jobs)
    f.write("Definition certs7 : list cert := [%s].\n\n" % "; ".join("cert7_j%03d" % j for j in range(jobs)))
    f.write("Lemma certs7_ok : certs_ok refs7 owners7 certs7 7 17 10 njobs7.\nProof.\n  split; [|split].\n")
    f.write("  - intros c Hc. unfold certs7 in Hc.\n")
    for j in range(jobs):
        f.write("    destruct Hc as [<-|Hc]; [split; [exact job7_j%03d_ok|repeat split]|].\n" % j)
    f.write("    destruct Hc.\n")
    f.write("  - intros s Hs. exists (nth s certs7 cert7_j000). split; [apply nth_In; exact Hs|].\n")
    f.write("    rewrite <- (map_nth c_shard certs7 cert7_j000 s).\n")
    f.write("    replace (map c_shard certs7) with (seq 0 %d) by reflexivity. apply seq_nth. exact Hs.\n" % jobs)
    f.write("  - exact owners7_bound.\nQed.\n")
print(jobs)
