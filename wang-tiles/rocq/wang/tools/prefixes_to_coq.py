#!/usr/bin/env python3
"""Write the reference list of reset prefixes (from tools/c/prefixes.c's output) as a Rocq file.

usage: prefixes_to_coq.py PREFIXES.txt OUT.v"""
import hashlib
import sys

src, out = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
rows = [list(map(int, l.split())) for l in raw.decode().split("\n") if l.strip()]
assert rows and all(len(r) == len(rows[0]) for r in rows)
o = open(out, "w")
o.write("(* generated by tools/prefixes_to_coq.py: the labels of cells 0..%d at each reset node, in walk\n" % (len(rows[0]) - 1))
o.write("   order (%d nodes). sha256 of the input: %s *)\n" % (len(rows), hashlib.sha256(raw).hexdigest()))
o.write("From Coq Require Import List.\nImport ListNotations.\n\n")
C = 500
names = []
for j in range(0, len(rows), C):
    nm = "refs7_%d" % (j // C)
    names.append(nm)
    o.write("Definition %s : list (list nat) := [%s].\n" % (nm, ";".join("[" + ";".join(map(str, r)) + "]" for r in rows[j:j + C])))
o.write("\nDefinition refs7 : list (list nat) := %s.\n" % " ++ ".join(names))
o.close()
print(len(rows), "prefixes")
