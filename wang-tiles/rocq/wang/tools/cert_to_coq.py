#!/usr/bin/env python3
"""Convert a wt_lazy certificate (PREFIX.tori, PREFIX.tree, each optionally .xz) into a Rocq data file.

usage: cert_to_coq.py PREFIX NAME OUT.v

The tree bytes are packed 7 per 63-bit integer, little-endian, in chunks; tori become lists
[a; b; s; cells...]. Nothing is changed or dropped: the Rocq checker reads the same bytes.
The header of OUT.v records the SHA-256 of the files read (of the .xz files when compressed)."""
import hashlib
import lzma
import os
import sys

prefix, name, out = sys.argv[1], sys.argv[2], sys.argv[3]


def load(path):
    if os.path.exists(path):
        raw = open(path, "rb").read()
        return raw, raw, os.path.basename(path)
    raw = open(path + ".xz", "rb").read()
    return lzma.decompress(raw), raw, os.path.basename(path) + ".xz"


tori_bytes, tori_raw, tori_name = load(prefix + ".tori")
data, tree_raw, tree_name = load(prefix + ".tree")
lines = tori_bytes.decode().split("\n")
head = lines[0].split()
assert head[:2] == ["wt-cert", "3"] and head[7] == "ringsym", head
n, d, ntori = int(head[3]), int(head[5]), int(head[9])
reset, shards, shard, gate = int(head[11]), int(head[13]), int(head[15]), int(head[17])
tori = [list(map(int, l.split())) for l in lines[1:] if l.strip()]
assert len(tori) == ntori
ntok = sum(1 for b in data if not b & 0x80)
# Cache size: any size is sound (a full cache only makes the check fail). Without resets the
# tables hold at most one entry per token; with resets they are cleared at every reset node, and
# 2^23 slots hold the largest subtree of the n = 7 certificate (2.5M relation pairs) at load < 0.35.
if reset:
    size = 1 << 23
else:
    size = 1
    while size < 2 * ntok + 16:
        size *= 2
words = [int.from_bytes(data[i:i + 7], "little") for i in range(0, len(data), 7)]

o = open(out, "w")
o.write("(* generated by tools/cert_to_coq.py\n")
o.write("   sha256 %s %s\n" % (tori_name, hashlib.sha256(tori_raw).hexdigest()))
o.write("   sha256 %s %s *)\n" % (tree_name, hashlib.sha256(tree_raw).hexdigest()))
o.write("From Coq Require Import List Uint63.\nImport ListNotations.\n")
o.write("From WangTiles Require Import Wang_Checker.\nLocal Open Scope uint63_scope.\n\n")
C = 4000
tree_names = []
for j in range(0, len(words), C):
    nm = "%s_t%d" % (name, j // C)
    tree_names.append(nm)
    o.write("Definition %s : list int := [%s].\n" % (nm, ";".join(map(str, words[j:j + C]))))
tori_names = []
cur, cnt = [], 0


def flush():
    global cur, cnt
    if cur:
        nm = "%s_g%d" % (name, len(tori_names))
        tori_names.append(nm)
        o.write("Definition %s : list (list int) := [%s].\n" % (nm, ";".join("[" + ";".join(map(str, t)) + "]" for t in cur)))
    cur, cnt = [], 0


for t in tori:
    cur.append(t)
    cnt += len(t)
    if cnt > C:
        flush()
flush()
o.write("\nDefinition %s : cert := mkCert %d %d %d %d %d %d [%s] %d %d [%s] %d.\n" % (
    name, n, d, reset, shards, shard, gate, ";".join(tree_names), len(data), ntori, ";".join(tori_names), size))
o.close()
print(name, "n", n, "D", d, "reset", reset, "shard", shard, "/", shards, "gate", gate, "bytes", len(data), "tokens", ntok, "tori", ntori, "cache", size)
