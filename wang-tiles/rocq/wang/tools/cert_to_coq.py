#!/usr/bin/env python3
"""Convert a wt_lazy certificate without resets (PREFIX.tori, PREFIX.tree, each optionally .xz) into a
Rocq data file (used for n = 5 and n = 6; n = 7 is made by tools/make_n7.sh).

usage: cert_to_coq.py PREFIX NAME OUT.v

The tree's tokens are Huffman coded and the tori packed as tools/wtcoq.py describes, in arrays of
2^16 integers. Nothing is changed or dropped: the Rocq checker reads the same
tokens. The header of OUT.v records the SHA-256 of the files read (of the .xz files when compressed)."""
import hashlib
import lzma
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wtcoq import HEAD, array_lit, chunks, huffman_encode, leb_tokens, outer_lit, pack_tori

prefix, name, out = sys.argv[1], sys.argv[2], sys.argv[3]


def load(path):
    if os.path.exists(path):
        raw = open(path, "rb").read()
        return raw, raw, os.path.basename(path)
    raw = open(path + ".xz", "rb").read()
    return lzma.decompress(raw), raw, os.path.basename(path) + ".xz"


tori_bytes, tori_raw, tori_name = load(prefix + ".tori")
data, tree_raw, tree_name = load(prefix + ".tree")
lines = tori_bytes.decode().split("\n")
head = lines[0].split()
assert head[:2] == ["wt-cert", "3"] and head[7] == "ringsym", head
n, d, ntori = int(head[3]), int(head[5]), int(head[9])
reset, shards, gate = int(head[11]), int(head[13]), int(head[17])
assert reset == 0 and shards == 1, "certificates with resets are made by tools/make_n7.sh"
tori = [list(map(int, l.split())) for l in lines[1:] if l.strip()]
assert len(tori) == ntori
ntok = sum(1 for b in data if not b & 0x80)
size = 1
while size < 2 * ntok + 16:
    size *= 2
tdata, toff = pack_tori(tori)

o = open(out, "w")
o.write("(* generated by tools/cert_to_coq.py\n")
o.write("   sha256 %s %s\n" % (tori_name, hashlib.sha256(tori_raw).hexdigest()))
o.write("   sha256 %s %s *)\n" % (tree_name, hashlib.sha256(tree_raw).hexdigest()))
o.write(HEAD + "From WangTiles Require Import Wang_Checker.\nLocal Open Scope uint63_scope.\n\n")


def arr(nm, xs):
    names = []
    for k, ch in enumerate(chunks(xs)):
        names.append("%s_%d" % (nm, k))
        o.write("Definition %s_%d : array int := %s.\n" % (nm, k, array_lit(ch)))
    return outer_lit(names)


toks = leb_tokens(data)
words, syms, counts = huffman_encode(toks)
t = arr(name + "_t", words)
hs = arr(name + "_s", syms)
o.write("Definition %s_h : array int := %s.\n" % (name, array_lit(counts)))
td = arr(name + "_d", tdata)
to = arr(name + "_o", toff)
o.write("Definition %s_u : array int := %s.\n" % (name, array_lit(list(range(ntori)))))
tu = name + "_u"
o.write("\nDefinition %s : cert := mkCert %d %d 0 0 %d %s %d %s_h %s %d %s %s %s %d %d.\n"
        % (name, n, d, gate, t, len(toks), name, hs, ntori, td, to, tu, ntori, size))
o.close()
print(name, "n", n, "D", d, "bytes", len(data), "tokens", ntok, "tori", ntori, "cache", size)
