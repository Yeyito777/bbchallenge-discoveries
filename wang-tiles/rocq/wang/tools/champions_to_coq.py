#!/usr/bin/env python3
"""Write Wang_Champions_Data.v from wang/certs/champions/*.tiles and *.tiling (tiles as on the wiki, [TOP,RIGHT,BOTTOM,LEFT])."""
import sys, os
src, out = sys.argv[1], sys.argv[2]
champs = [("wiki_n5", "wiki_n5_d6", 6), ("wiki_n6", "wiki_n6_d8", 8), ("n7", "n7_d16", 16), ("n8", "n8_d17", 17)]
o = open(out, "w")
o.write("(* generated by tools/champions_to_coq.py from wang/certs/champions *)\n")
o.write("From Coq Require Import List.\nImport ListNotations.\nFrom WangTiles Require Import WangTiles_Statement.\n\n")
for name, f, d in champs:
    tiles = [tuple(int(x) for x in t.strip("[]").split(",")) for t in open(os.path.join(src, f + ".tiles")).read().split()]
    rows = [list(map(int, l.split())) for l in open(os.path.join(src, "%s.d%d.tiling" % (f, d))) if l.strip()]
    assert len(rows) == d and all(len(r) == d for r in rows), f
    o.write("Definition %s_tiles : list tile := [%s].\n" % (name, "; ".join("mk_tile %d %d %d %d" % t for t in tiles)))
    o.write("Definition %s_tiling : list (list nat) := [\n  %s].\n\n" % (name, ";\n  ".join("[" + ";".join(map(str, r)) + "]" for r in rows)))
o.close()
